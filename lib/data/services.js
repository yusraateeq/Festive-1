export const serviceBySlug = (slug) => services.find((s) => s.slug === slug);

/* JSON-LD Service + Offer schemas per service */
export function serviceLd(service, domain, path) {
  return {
    '@type': 'Service',
    '@id': `${domain}${path}#service`,
    name: service.name,
    serviceType: service.name,
    description: service.short,
    url: `${domain}${path}`,
    provider: { '@id': `${domain}/#organization` },
    areaServed: [
      'Dubai',
      'Abu Dhabi',
      'Sharjah',
      'Ajman',
      'Umm Al Quwain',
      'Ras Al Khaimah',
      'Fujairah',
      'United Arab Emirates',
    ],
    hasOfferCatalog: {
      '@type': 'OfferCatalog',
      name: `${service.name} packages`,
      itemListElement: {
        '@type': 'Offer',
        priceCurrency: 'AED',
        price: service.priceFrom.replace(/[^0-9.,]/g, '').replace('Custom', '0') || '0',
        description: service.short,
      },
    },
  };
}